#!/usr/bin/env bash
# Builds mikrotik_lite.yml: a slim copy of snmp_exporter's bundled "mikrotik" module (DT-023).
#
# The bundled module walks the whole MIKROTIK-MIB enterprise tree (1.3.6.1.4.1.14988): ~2,400 PDUs
# per CRS3xx switch (modem, CAPsMAN, GPS, partitions, gauges, optics and 72 interface-stats columns),
# which takes 5-12 s on RouterOS and pushed scrapes into the 20 s timeout. mikrotik_lite keeps the
# metric definitions (names, types, indexes, lookups) of the bundled module but only for what the
# "MikroTik SNMP" dashboard (dashboards/Network/mikrotik-snmp.json) queries and the switches answer,
# and walks those OIDs only; scalars are fetched with one GET. max_repetitions 50 (default 25) gets each
# ~29-row column in one GETBULK: measured on the switches, median walk 10.0 s -> 5.5 s, max 17.6 s -> 8.0 s.
#
# Regenerate after bumping var.images.snmp_exporter (the input is that image's /etc/snmp_exporter/snmp.yml):
#   podman run --rm --entrypoint cat docker.io/prom/snmp-exporter:<tag> /etc/snmp_exporter/snmp.yml > /tmp/snmp.yml
#   nix-shell -p yq-go --run 'bash build-mikrotik-lite.sh /tmp/snmp.yml > mikrotik_lite.yml'
# To add a metric: put its name in KEEP, regenerate, apply monitoring-config.
set -euo pipefail
src=${1:?usage: build-mikrotik-lite.sh path/to/bundled/snmp.yml}

KEEP='
mtxrBoardName mtxrSerialNumber mtxrFirmwareVersion mtxrNote mtxrUSBPowerReset
mtxrLicLevel mtxrLicSoftwareId mtxrLicUpgradableTo mtxrLicVersion
mtxrHlTemperature mtxrHlProcessorTemperature mtxrHlActiveFan mtxrHlVoltage mtxrHlProcessorFrequency
mtxrNeighborIdentity mtxrNeighborMacAddress mtxrNeighborIpAddress mtxrNeighborPlatform
mtxrNeighborSoftwareID mtxrNeighborVersion
mtxrInterfaceStatsLinkDowns
mtxrInterfaceStatsRxBytes mtxrInterfaceStatsTxBytes
mtxrInterfaceStatsRxDrop mtxrInterfaceStatsTxDrop
mtxrInterfaceStatsRxFCSError mtxrInterfaceStatsTxFCSError
mtxrInterfaceStatsRxAlignError mtxrInterfaceStatsRxCarrierError
mtxrInterfaceStatsRxControl mtxrInterfaceStatsTxControl
mtxrInterfaceStatsRxFragment mtxrInterfaceStatsTxFragment
mtxrInterfaceStatsRxJabber mtxrInterfaceStatsTxJabber
mtxrInterfaceStatsRxLengthError mtxrInterfaceStatsRxOverflow
mtxrInterfaceStatsRxPause mtxrInterfaceStatsTxPause mtxrInterfaceStatsTxPauseHonored
mtxrInterfaceStatsRxTooLong mtxrInterfaceStatsTxTooLong
mtxrInterfaceStatsRxTooShort mtxrInterfaceStatsTxTooShort
mtxrInterfaceStatsRxUnknownOp mtxrInterfaceStatsTxUnderrun
mtxrInterfaceStatsTxCollision mtxrInterfaceStatsTxTotalCollision mtxrInterfaceStatsTxSingleCollision
mtxrInterfaceStatsTxMultipleCollision mtxrInterfaceStatsTxLateCollision mtxrInterfaceStatsTxExcessiveCollision
mtxrInterfaceStatsTxDeferred mtxrInterfaceStatsTxExcessiveDeferred
'
keep_json=$(printf '"%s",' $KEEP | sed 's/,$//; s/^/[/; s/$/]/')

KEEP_JSON="$keep_json" SRC="$src" yq -n --prettyPrint '
  (load(env(SRC)).modules.mikrotik.metrics) as $all |
  env(KEEP_JSON) as $keep |
  ($all | map(select(.name as $n | $keep | contains([$n])))) as $m |
  {"modules": {"mikrotik_lite": {
    "max_repetitions": 50,
    "get":  ($m | map(select(has("indexes") | not) | .oid + ".0") | unique),
    "walk": (($m | map(select(has("indexes")) | .oid)) +
             ($m | map(.lookups // [] | .[] | select(has("oid")) | .oid)) | unique),
    "metrics": $m
  }}}
' | { echo "# Generated by build-mikrotik-lite.sh from snmp_exporter's bundled snmp.yml (module \"mikrotik\"). Do not edit; edit KEEP and regenerate."; cat; }

# Fail if a KEEP name doesn't exist in the bundled module (typo or a MIB change).
missing=$(for n in $KEEP; do SRC="$src" N="$n" yq -e '.modules.mikrotik.metrics[] | select(.name == env(N)) | .name' "$src" >/dev/null 2>&1 || echo "$n"; done)
if [ -n "$missing" ]; then echo "build-mikrotik-lite.sh: not in the bundled mikrotik module: $missing" >&2; exit 1; fi
