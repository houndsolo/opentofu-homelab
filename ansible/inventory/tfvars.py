#!/usr/bin/env python3
"""Ansible dynamic inventory for the Proxmox hosts, read from the repo's shared tfvars.

Source: inventory/auto.tfvars/nodes.auto.tfvars (the same `nodes` variable the roots use).
Address = cidrhost(nodes.management_prefix, id), the expression the tofu roots connect with, so the
inventory can't drift from the repo. Groups:
  pve         every host in nodes.proxmox
  cluster     hosts without standalone = true (id order = reboot.yml order)
  ceph        same as cluster (every cluster node runs Ceph)
  standalone  hosts with standalone = true (greatfox)
Hosts that aren't Proxmox nodes (gf.pbs) live in static.yml next to this script.

  ./tfvars.py --list          JSON for Ansible (what ansible-playbook calls)
  ./tfvars.py --host NAME     {} (host vars are all in _meta)
  ./tfvars.py --yaml          the same inventory as a static hosts.yml, for reading/debugging
Needs python-hcl2 (the repo's shell.nix provides it).
"""
import argparse
import ipaddress
import json
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[2]
NODES_TFVARS = REPO / "inventory/auto.tfvars/nodes.auto.tfvars"


def unquote(value):
    # python-hcl2 can hand back strings with their HCL quotes; strip them.
    if isinstance(value, str) and len(value) >= 2 and value[0] == value[-1] == '"':
        return json.loads(value)
    return value


def load_nodes(path=NODES_TFVARS):
    import hcl2
    with open(path) as source:
        data = hcl2.load(source)
    nodes = data["nodes"]
    prefix = ipaddress.ip_network(unquote(nodes["management_prefix"]))
    hosts = []
    for name, node in nodes["proxmox"].items():
        name = unquote(name)
        node_id = int(node["id"])
        standalone = node.get("standalone", False)
        if isinstance(standalone, str):
            standalone = unquote(standalone).lower() == "true"
        hosts.append({"name": name, "id": node_id, "standalone": bool(standalone),
                      "address": str(prefix[node_id])})
    hosts.sort(key=lambda h: h["id"])
    return hosts


def build(hosts):
    cluster = [h["name"] for h in hosts if not h["standalone"]]
    standalone = [h["name"] for h in hosts if h["standalone"]]
    return {
        "_meta": {"hostvars": {h["name"]: {"ansible_host": h["address"], "pve_node_id": h["id"]} for h in hosts}},
        "all": {"children": ["pve", "cluster", "ceph", "standalone"], "vars": {"ansible_user": "root"}},
        "pve": {"hosts": [h["name"] for h in hosts]},
        "cluster": {"hosts": cluster},
        "ceph": {"hosts": list(cluster)},
        "standalone": {"hosts": standalone},
    }


def to_yaml(inventory):
    hostvars = inventory["_meta"]["hostvars"]
    lines = ["# Generated by ansible/inventory/tfvars.py --yaml from inventory/auto.tfvars/nodes.auto.tfvars.",
             "all:", "  vars:", "    ansible_user: root", "  children:"]
    for group in inventory["all"]["children"]:
        lines += [f"    {group}:", "      hosts:"]
        for name in inventory[group]["hosts"]:
            lines.append(f"        {name}:")
            if group == "pve":
                for key, value in hostvars[name].items():
                    lines.append(f"          {key}: {value}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--list", action="store_true")
    mode.add_argument("--host")
    mode.add_argument("--yaml", action="store_true")
    parser.add_argument("--file", type=Path, default=NODES_TFVARS, help=argparse.SUPPRESS)
    args = parser.parse_args()
    try:
        inventory = build(load_nodes(args.file))
    except ImportError:
        sys.exit("python-hcl2 is missing: run inside the repo shell (direnv or nix-shell)")
    if args.host is not None:
        print("{}")
    elif args.yaml:
        sys.stdout.write(to_yaml(inventory))
    else:
        print(json.dumps(inventory, indent=2))


if __name__ == "__main__":
    main()
